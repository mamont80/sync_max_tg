namespace SyncMax.Services.Moderation;

/// <summary>
/// Таблица визуально неразличимых символов (confusables) — ядро защиты от подмены букв.
///
/// Обычной юникод-нормализации (NFKC/NFKD) здесь НЕ хватает принципиально: она работает
/// внутри одного набора символов и, например, кириллическую «а» (U+0430) к латинской «a»
/// (U+0061) не приводит — это разные буквы, а не разные записи одной. Для схлопывания
/// межалфавитных подмен нужен отдельный этап, описанный в UTS #39 (алгоритм skeleton
/// и файл confusables.txt).
///
/// Здесь не весь confusables.txt (~6500 записей), а выборка под нашу задачу: латиница,
/// греческий, «экзотическая» кириллица и цифро-символьные замены (leet). Именно ими
/// подменяют буквы в русских и английских словах; полная таблица Unicode нужна была бы
/// ради алфавитов, которых в переписке не бывает. Расширять — дописывая пары ниже.
///
/// У каждого символа РОВНО ОДИН канонический вид, и это важнее, чем направление замены:
/// если бы, например, латинские «c» и «s» сошлись в один символ, «sock» и «cock» стали бы
/// неразличимы. Поэтому пары ниже перечислены поимённо, а не сжатыми строками.
/// </summary>
internal static class Confusables
{
    /*
       Основная таблица. Сюда попадают только замены, ОДИНАКОВЫЕ для обоих регистров:
       у латинских a, c, e, o, p, x, y кириллический двойник есть и у строчной формы, и у
       заглавной, поэтому итог не зависит от того, применить замену до или после lowercase.

       Буквы с диакритикой (é, ï) и составные (й = и + кратка, ё = е + умлаут) здесь не
       нужны: их разбирает и убирает NFKD в TextNormalizer.
    */
    private static readonly Dictionary<char, char> Map = new()
    {
        // --- Латиница → кириллица ---
        ['a'] = 'а', ['c'] = 'с', ['e'] = 'е', ['o'] = 'о', ['p'] = 'р', ['x'] = 'х', ['y'] = 'у',
        ['A'] = 'А', ['C'] = 'С', ['E'] = 'Е', ['O'] = 'О', ['P'] = 'Р', ['X'] = 'Х', ['Y'] = 'У',

        // --- «Экзотическая» кириллица → латиница (похожи на латинские буквы,
        //     у которых кириллического двойника нет) ---
        ['ѕ'] = 's', ['Ѕ'] = 'S',   // дзе
        ['і'] = 'i', ['І'] = 'I',   // украинское/белорусское и
        ['ј'] = 'j', ['Ј'] = 'J',
        ['һ'] = 'h', ['Һ'] = 'H',
        ['ԁ'] = 'd', ['ԛ'] = 'q', ['ԝ'] = 'w',
        ['ӏ'] = 'l', ['ѵ'] = 'v',

        // --- Греческий ---
        ['α'] = 'а', ['ο'] = 'о', ['ε'] = 'е', ['ρ'] = 'р', ['χ'] = 'х', ['υ'] = 'у',
        ['κ'] = 'к', ['μ'] = 'м', ['τ'] = 'т', ['ι'] = 'i', ['ν'] = 'v', ['β'] = 'в',
        ['Α'] = 'А', ['Ε'] = 'Е', ['Κ'] = 'К', ['Μ'] = 'М', ['Ο'] = 'О', ['Ρ'] = 'Р',
        ['Τ'] = 'Т', ['Χ'] = 'Х', ['Υ'] = 'У', ['Ι'] = 'I', ['Β'] = 'В', ['Η'] = 'Н',

        // --- Цифры и знаки (leet) ---
        // Только однозначные замены: одна цифра не может претендовать сразу на две буквы.
        // «3» отдана русской «з» (по начертанию), поэтому английское «sh3t» этим слоем
        // не ловится — осознанный размен в пользу русского языка.
        ['0'] = 'о', ['1'] = 'i', ['3'] = 'з', ['4'] = 'ч', ['5'] = 's', ['6'] = 'б',
        ['@'] = 'а', ['$'] = 's', ['!'] = 'i', ['|'] = 'i', ['₽'] = 'р'
    };

    /*
       Заглавные латинские B, H, K, M, T неотличимы от кириллических В, Н, К, М, Т, а вот их
       строчные формы (b, h, k, m, t) — уже нет. Замену пришлось бы делать до lowercase, и
       тогда одно и то же английское слово нормализовалось бы по-разному в зависимости от
       регистра: «bitch» → «bitсh», а «BITCH» → «вiтсн». Совпасть со словарём смогло бы
       только одно из них.

       Поэтому такие замены применяются лишь к словам СМЕШАННОГО алфавита — где латиница
       соседствует с кириллицей. Смешение алфавитов внутри слова само по себе признак
       подмены (mixed-script detection в UTS #39): «MУДАК» с латинской M — подмена,
       а «BITCH» целиком латиницей — обычное английское слово.
    */
    private static readonly Dictionary<char, char> MixedScriptMap = new()
    {
        ['B'] = 'В', ['H'] = 'Н', ['K'] = 'К', ['M'] = 'М', ['T'] = 'Т'
    };

    /// <summary>
    /// Канонический вид символа; символ без двойников возвращается как есть.
    /// <paramref name="mixedScript"/> — слово содержит буквы разных алфавитов, см.
    /// <see cref="MixedScriptMap"/>.
    /// </summary>
    public static char Canonical(char c, bool mixedScript)
    {
        if (mixedScript && MixedScriptMap.TryGetValue(c, out var upper))
            return upper;

        return Map.TryGetValue(c, out var mapped) ? mapped : c;
    }
}
