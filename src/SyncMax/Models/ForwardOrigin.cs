namespace SyncMax.Models;

/// <summary>
/// Откуда сообщение было переслано (репостнуто) в исходный чат — платформо-независимо.
/// Заполняется на приёме соответствующим <c>*BotService</c>, а
/// <see cref="Services.MessageRelayService"/> показывает это отдельной строкой «шапки»:
/// без неё пересланная копия выглядит как собственное сообщение отправителя, и понять,
/// что это репост и откуда, невозможно.
///
/// Полнота данных у платформ разная, поэтому оба поля необязательны:
/// <list type="bullet">
/// <item>Telegram отдаёт всё — название канала/чата или имя автора и, для публичных
/// каналов, ссылку на само сообщение.</item>
/// <item>MAX в <c>link.forward</c> присылает только текст и вложения оригинала: ни
/// исходного чата, ни автора там нет. Для него известен лишь сам факт пересылки.</item>
/// </list>
/// </summary>
public sealed class ForwardOrigin
{
    /// <summary>Название канала/чата или имя автора оригинала; null — источник неизвестен.</summary>
    public string? Title { get; init; }

    /// <summary>
    /// Ссылка на исходное сообщение, если платформа позволяет её построить.
    /// В «шапке» ею оформляется <see cref="Title"/>.
    /// </summary>
    public string? Url { get; init; }
}
